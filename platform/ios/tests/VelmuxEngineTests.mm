#pragma mark - 5. Lifecycle: a mid-run cancel is honest

- (void)testLifecycle_cancelIsHonest {
  NSString *dir = [VLMXTestMedia freshWorkDirectory:@"cancel"];
  // Long enough that the transcode is still running when the cancel lands.
  NSError *fixtureError = nil;
  VLMXGeneratedMedia *fixture = [VLMXTestMedia
      generateH264AacMp4AtPath:[dir stringByAppendingPathComponent:@"fixture.mp4"]
                         width:640
                        height:480
                     frameRate:24.0
                    frameCount:300
                         error:&fixtureError];
  XCTAssertNotNil(fixture, @"fixture generation failed: %@",
                  fixtureError.localizedDescription);
  if (fixture == nil) {
    return;
  }

  VelmuxEngineHandle *engine = vlmxCreateFacadeEngine(@"cancel-engine");
  XCTAssertTrue(engine != nullptr, @"engine construction failed");
  if (engine == nullptr) {
    return;
  }
  @try {
    // A real transcode (explicit bitrates invalidate stream copy) through
    // whichever backend this build has.
    NSString *request = [NSString stringWithFormat:
        @"{"
         @"\"source\":{\"uri\":\"%@\",\"displayName\":\"fixture.mp4\"},"
         @"\"outputContainer\":\"mp4\","
         @"\"goal\":{\"kind\":\"custom\"},"
         @"\"video\":{\"codec\":\"h264\",\"enabled\":true,"
         @"\"rateControl\":\"bitrate\",\"bitRate\":800000},"
         @"\"audio\":{\"codec\":\"aac\",\"enabled\":true,\"bitRate\":64000},"
         @"\"subtitles\":{\"policy\":\"remove\"},"
         @"\"processingMode\":\"auto\""
         @"}",
        fixture.path];
    char *startedRaw = velmux_start_job(engine, request.UTF8String);
    NSString *started =
        startedRaw != nullptr ? [NSString stringWithUTF8String:startedRaw]
                              : @"";
    if (startedRaw != nullptr) {
      velmux_free_string(startedRaw);
    }
    NSString *jobId = vlmxJsonStringField(started, @"jobId");
    XCTAssertNotNil(jobId, @"startJob returned: %@", started);
    if (jobId == nil) {
      return;
    }

    // Wait until the job is actually executing, then cancel mid-run.
    NSString *state = nil;
    const NSTimeInterval deadline =
        [NSDate timeIntervalSinceReferenceDate] + 120.0;
    for (;;) {
      char *raw = velmux_get_job(engine, jobId.UTF8String);
      NSString *snapshot =
          raw != nullptr ? [NSString stringWithUTF8String:raw] : @"";
      if (raw != nullptr) {
        velmux_free_string(raw);
      }
      state = vlmxJsonStringField(snapshot, @"state");
      NSString *errorField = vlmxJsonStringField(snapshot, @"error");
      if ([state isEqualToString:@"failed"]) {
        XCTFail(@"the job failed before it could be canceled: %@",
                errorField);
        return;
      }
      if ([state isEqualToString:@"running"]) {
        break;
      }
      if ([NSDate timeIntervalSinceReferenceDate] > deadline) {
        XCTFail(@"job never reached the running state (last: %@)", state);
        return;
      }
      [NSThread sleepForTimeInterval:0.025];
    }

    const int cancelRc = velmux_cancel_job(engine, jobId.UTF8String);
    XCTAssertEqual(cancelRc, 1, @"cancel must be recorded while running");

    // The durable state flips to Canceled immediately; the worker unwinds
    // cooperatively. Wait for the terminal record and for the worker to be
    // fully done (is_job_active == 0) before judging.
    NSString *finalState = state;
    const NSTimeInterval terminalDeadline =
        [NSDate timeIntervalSinceReferenceDate] + 120.0;
    for (;;) {
      char *raw = velmux_get_job(engine, jobId.UTF8String);
      NSString *snapshot =
          raw != nullptr ? [NSString stringWithUTF8String:raw] : @"";
      if (raw != nullptr) {
        velmux_free_string(raw);
      }
      finalState = vlmxJsonStringField(snapshot, @"state");
      if ([finalState isEqualToString:@"completed"] ||
          [finalState isEqualToString:@"failed"] ||
          [finalState isEqualToString:@"canceled"]) {
        break;
      }
      if ([NSDate timeIntervalSinceReferenceDate] > terminalDeadline) {
        XCTFail(@"job never reached a terminal state after cancel (last: %@)",
                finalState);
        return;
      }
      [NSThread sleepForTimeInterval:0.05];
    }
    const NSTimeInterval activeDeadline =
        [NSDate timeIntervalSinceReferenceDate] + 120.0;
    while (velmux_is_job_active(engine, jobId.UTF8String) == 1) {
      if ([NSDate timeIntervalSinceReferenceDate] > activeDeadline) {
        XCTFail(@"the worker never unwound after the cancel");
        return;
      }
      [NSThread sleepForTimeInterval:0.05];
    }

    // The honest outcome: Canceled, never a Completed record for a run the
    // user stopped.
    XCTAssertTrue([finalState isEqualToString:@"canceled"],
                  @"a canceled mid-run job finalized as '%@' (must be "
                  @"canceled)",
                  finalState);
    XCTAssertFalse([finalState isEqualToString:@"completed"],
                   @"a canceled mid-run job must never be Completed");
  } @finally {
    velmux_engine_destroy(engine);
  }
}

