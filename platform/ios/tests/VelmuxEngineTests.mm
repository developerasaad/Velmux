// VelmuxEngineTests — REAL engine execution on the iOS simulator.
//
// What this suite proves, with real media generated on-simulator
// (VelmuxTestMedia: AVAssetWriter H.264+AAC MP4 fixtures) and independent
// validation (fresh AVURLAsset/AVAssetReader probes, never the producer):
//
//   1. testFFtoF_engineTranscode — a whole-pipeline FFmpeg transcode
//      (H.264+AAC -> H.264+AAC) through the SAME engine construction the
//      app host uses (the C facade, velmux_engine_create). The request
//      forces a real re-encode (explicit video+audio bitrates make stream
//      copy invalid) and preferSoftware biases the planner to FFmpeg; the
//      assertion on the pipeline summary proves FFmpeg actually ran.
//
//   2. testNtoN_stageComposed — an all-Apple stage pipeline (Demux/Decode/
//      VideoProcessing/AudioProcessing/Encode/Mux/Bitstream -> Apple)
//      executed by the REAL velmux::core::HybridExecutor: AVAssetReader
//      stage decode -> VideoToolbox stage encode -> AVAssetWriter stage
//      mux with stream-copied AAC. The output is probed and a few frames
//      are decoded through an independent AVAssetReader.
//
//   3. testFtoN_ffv1ForcesHybrid — job 1 produces an FFV1-in-MKV
//      intermediate through the natural engine path (FFmpeg is the only
//      backend that encodes FFV1). Job 2 proves the F->N composition
//      (FFmpeg stage decode -> Apple VideoToolbox HEVC stage encode).
//      IOS HONESTY NOTE: the task's natural FFV1 -> HEVC route is honestly
//      INFEASIBLE on iOS — the planner requires the hybrid MUX side to
//      read the source container (Apple/AVFoundation cannot demux MKV), so
//      no hybrid candidate exists for an MKV source. The F->N composition
//      is therefore forced on the original H.264 fixture with the same
//      documented route-selection scaffolding as N->F (below); job 1 still
//      proves the FFV1 encode and the FFmpeg-only route end-to-end.
//
//   4. testNtoF_maskedForcesHybrid — the Apple stage decode -> FFmpeg
//      (libx264) stage encode composition.
//
//   5. testLifecycle_cancelIsHonest — a mid-run cancel must finalize as
//      Canceled, never Completed.
//
// TEST SCAFFOLDING (route selection only, never fake media work): the
// masked-engine tests wrap the REAL backends behind test-only IBackend
// forwarders that NARROW the capability reports the planner reads, so no
// single-backend route exists and the hybrid pipeline is the only plan:
//
//   - F->N: the FFmpeg wrapper hides its video ENCODERS (FFmpeg keeps the
//     real decode stage side); the Apple wrapper hides its video DECODERS
//     (Apple keeps the real encode/mux stage side) and its whole-pipeline
//     executor reports canExecute=false.
//   - N->F: the FFmpeg wrapper hides its video DECODERS (FFmpeg keeps the
//     real encode stage side); the Apple wrapper hides its video ENCODERS
//     (Apple keeps the real decode stage side) and its whole-pipeline
//     executor reports canExecute=false.
//
// Every frame still crosses the real CPU-frame interchange between the
// real FFmpeg and Apple stage workers; the engine, planner, job manager,
// scheduler, stores and hybrid executor are the production objects. Audio
// is disabled in the masked tests: with identical in/out codecs and
// container, stream copy would otherwise be the (correct) cheapest plan,
// and v1 hybrid stream-copies audio anyway.
//
// The "pipelineSummary contains Hybrid" assertions prove the PLANNER chose
// a hybrid composition — not merely that a conversion succeeded.
//
// FFmpeg-dependent tests skip honestly (XCTSkip) when the engine was built
// without the FFmpeg backend (fork PRs without the pinned artifacts) or
// when the simulator runtime lacks the codec under test.
