                job.error.c_str(), job.state.c_str());
  NSString *summary =
      [NSString stringWithUTF8String:job.pipelineSummary.c_str()];
  XCTAssertNotNil(summary);
  XCTAssertTrue([summary localizedCaseInsensitiveContainsString:@"hybrid"],
                @"the planner did not choose a hybrid pipeline: \"%@\"",
                summary);
  XCTAssertTrue([summary localizedCaseInsensitiveContainsString:
                        @"ffmpeg decode"],
                @"the hybrid decode side is not FFmpeg: \"%@\"", summary);
  XCTAssertTrue([summary localizedCaseInsensitiveContainsString:
                        @"apple encode"],
                @"the hybrid encode side is not Apple: \"%@\"", summary);

  // INDEPENDENT validation of the HEVC output.
  NSString *outPath = [NSString stringWithUTF8String:job.outputPath.c_str()];
  XCTAssertGreaterThan([VLMXTestMedia fileSizeAtPath:outPath], (long long)0,
                       @"output missing or empty: %@", outPath);
  NSError *probeError = nil;
  VLMXMediaProbe *probe = [VLMXTestMedia probeAtPath:outPath
                                               error:&probeError];
  XCTAssertNotNil(probe, @"probe failed: %@", probeError);
  if (probe != nil) {
    XCTAssertTrue([probe.videoCodec isEqualToString:@"hvc1"] ||
                      [probe.videoCodec isEqualToString:@"hev1"],
                  @"expected HEVC video, got %@", probe.videoCodec);
    XCTAssertEqual(probe.width, fixture.width, @"geometry changed");
    XCTAssertEqual(probe.height, fixture.height, @"geometry changed");
    [self vlmxAssertDurationWithin:probe.durationUs
                            expected:fixture.durationUs
                               label:@"F->N"];
  }
