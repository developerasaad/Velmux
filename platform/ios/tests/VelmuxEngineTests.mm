            @"(VTCompressionSessionCreate for kCMVideoCodecType_HEVC "
            @"failed); the F->N target codec cannot be encoded");
  }

  NSString *dir = [VLMXTestMedia freshWorkDirectory:@"fton"];
  NSError *fixtureError = nil;
  VLMXGeneratedMedia *fixture = [VLMXTestMedia
      generateH264AacMp4AtPath:[dir stringByAppendingPathComponent:@"fixture.mp4"]
                         width:320
                        height:240
                     frameRate:24.0
                    frameCount:240
                         error:&fixtureError];
  XCTAssertNotNil(fixture, @"fixture generation failed: %@",
                  fixtureError.localizedDescription);
  if (fixture == nil) {
    return;
  }

  // ---- Job 1 (real engine, natural path): fixture -> FFV1 in MKV. -----
  // FFmpeg is the only backend that encodes FFV1; Apple cannot, so the
  // planner's only route is the FFmpeg whole-pipeline transcode.
  VelmuxEngineHandle *engine = vlmxCreateFacadeEngine(@"fton-engine");
  XCTAssertTrue(engine != nullptr, @"engine construction failed");
  NSString *ffv1Path = @"";
  @try {
    if (!vlmxFfmpegBackendPresent(engine)) {
      XCTSkip(@"the engine was built without the FFmpeg backend; the FFV1 "
              @"intermediate cannot be produced");
    }
    NSString *ffv1Request = [NSString stringWithFormat:
        @"{"
         @"\"source\":{\"uri\":\"%@\",\"displayName\":\"fixture.mp4\"},"
         @"\"outputContainer\":\"mkv\","
         @"\"goal\":{\"kind\":\"custom\"},"
         @"\"video\":{\"codec\":\"ffv1\",\"enabled\":true},"
         @"\"audio\":{\"codec\":\"aac\",\"enabled\":true},"
         @"\"subtitles\":{\"policy\":\"remove\"},"
         @"\"processingMode\":\"auto\""
         @"}",
        fixture.path];
    const VLMXFacadeJob ffv1Job = vlmxRunFacadeJob(engine, ffv1Request, 300.0);
    XCTAssertTrue([@"completed" isEqualToString:
                       [NSString stringWithUTF8String:ffv1Job.state.c_str()]],
                  @"FFV1 intermediate failed: %s (summary: %s)",
                  ffv1Job.error.c_str(), ffv1Job.pipelineSummary.c_str());
    ffv1Path = [NSString stringWithUTF8String:ffv1Job.outputPath.c_str()];
    // AVFoundation cannot demux MKV/FFV1, so the intermediate is validated
    // by the engine's own completed state + a real size + (below) the
    // masked run's H.264 source, which the FFmpeg stage worker fully
    // decodes. (The FFV1 file itself is decoded by nothing on iOS — that
    // is precisely why FFV1 sources have no Apple route.)
    XCTAssertGreaterThan([VLMXTestMedia fileSizeAtPath:ffv1Path],
                         (long long)1024,
                         @"FFV1 intermediate missing or empty: %@", ffv1Path);
  } @finally {
    velmux_engine_destroy(engine);
  }

  // ---- Job 2: the F->N composition (FFmpeg decode -> Apple HEVC encode).
  // See the file header: the natural FFV1 -> HEVC route is honestly
  // infeasible on iOS (the planner requires the hybrid mux side to read
  // the source container; Apple cannot demux MKV), so the F->N composition
  // is forced on the original fixture with the documented route-selection
  // masks. The FFmpeg stage decoder and the Apple stage encoder/muxer are
  // the real workers.
  const VLMXMaskedJob job = vlmxRunMaskedHybridJob(
      fixture.path, VLMXHybridDirection::FfmpegToApple,
      velmux::core::VideoCodec::HEVC, 800000, @"fton-masked");
