#pragma mark - 3. F->N: FFV1 forces the FFmpeg-only route, then the hybrid

- (void)testFtoN_ffv1ForcesHybrid {
#if !VELMUX_TEST_FFMPEG_BACKEND
  XCTSkip(@"the engine was built without the FFmpeg backend "
          @"(VELMUX_FFMPEG_ROOT not set at pod install); neither the FFV1 "
          @"encode nor the F->N hybrid route can exist");
#else
  // The F->N composition ends in a VideoToolbox HEVC encode: probe the
  // runtime first (Intel simulators and some runtime images lack it).
  if (!vlmxVtCanEncode(kCMVideoCodecType_HEVC)) {
