#if VELMUX_TEST_FFMPEG_BACKEND
static VLMXMaskedJob vlmxRunMaskedHybridJob(NSString *fixturePath,
                                            VLMXHybridDirection direction,
                                            velmux::core::VideoCodec outCodec,
                                            std::int64_t videoBitRate,
                                            NSString *workLabel) {
  VLMXMaskedJob outcome;
  // The real backends outlive the engine (the engine keeps raw pointers
  // into them through the wrappers).
  velmux::apple::AppleBackend realApple;
  velmux::ffmpeg::FfmpegBackend realFfmpeg;
  {
    velmux::core::EngineConfig config;
    config.dataDir = std::string([VLMXTestMedia freshWorkDirectory:workLabel]
                                     .UTF8String);
    std::vector<std::unique_ptr<velmux::backend::IBackend>> backends;
    backends.push_back(
        std::make_unique<VLMXMaskedAppleBackend>(realApple, direction));
    backends.push_back(
        std::make_unique<VLMXMaskedFfmpegBackend>(realFfmpeg, direction));
    auto engine =
        velmux::core::VelmuxEngine::create(config, std::move(backends));
    if (engine == nullptr) {
      outcome.state = "failed";
      outcome.error = "cannot construct the masked test engine";
      return outcome;
    }

    velmux::core::ConversionRequest request;
    request.source.uri = std::string(fixturePath.UTF8String);
    request.source.displayName = "fixture.mp4";
    request.outputContainer = velmux::core::Container::Mp4;
    request.goal.kind = velmux::core::GoalKind::Custom;
    request.video.enabled = true;
    request.video.codec = outCodec;
    request.video.rateControl = velmux::core::RateControl::Bitrate;
    request.video.bitRate = videoBitRate;
    // Audio disabled: identical in/out codec+container would otherwise
    // stream-copy (correct behavior, but not the hybrid path under test).
    request.audio.enabled = false;
    request.subtitles.policy = velmux::core::SubtitlePolicy::Remove;
    request.processingMode = velmux::core::ProcessingMode::Auto;

    const auto jobId = engine->startJob(request);
    if (!jobId.ok()) {
      outcome.state = "failed";
      outcome.error = jobId.error().message;
      return outcome;
    }
    const NSTimeInterval deadline =
        [NSDate timeIntervalSinceReferenceDate] + 300.0;
    for (;;) {
      const auto snapshot = engine->getJob(jobId.value());
      if (!snapshot.has_value()) {
        outcome.state = "failed";
        outcome.error = "job record vanished";
        return outcome;
      }
      outcome.state = velmux::core::jobStateName(snapshot->state);
      outcome.outputPath = snapshot->outputPath;
      outcome.error = snapshot->error;
      outcome.pipelineSummary = snapshot->pipelineSummary;
      const std::string state = outcome.state;
      if (state == "completed" || state == "failed" || state == "canceled") {
        outcome.ok = state == "completed";
        return outcome;
      }
      if ([NSDate timeIntervalSinceReferenceDate] > deadline) {
        outcome.error = "timed out waiting for a terminal state";
        return outcome;
      }
      [NSThread sleepForTimeInterval:0.05];
    }
  }
}
