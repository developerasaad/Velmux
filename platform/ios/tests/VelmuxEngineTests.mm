namespace {

/// Which hybrid composition the masks must leave as the ONLY route.
enum class VLMXHybridDirection {
  FfmpegToApple, // FFmpeg stage decode -> Apple stage encode
  AppleToFfmpeg, // Apple stage decode -> FFmpeg stage encode
};

/// A whole-pipeline executor that honestly refuses everything: even if
/// some future planner change routed a single-backend pipeline here, the
/// job would fail loudly instead of silently executing the masked side.
class VLMXRefusingExecutor final : public velmux::backend::IPipelineExecutor {
public:
  bool canExecute(const velmux::core::Pipeline &,
                  const velmux::core::ConversionRequest &) const override {
    return false;
  }
  velmux::backend::ExecuteResult
  execute(const velmux::backend::ExecuteParams &) override {
    velmux::backend::ExecuteResult result;
    result.error = velmux::core::Error::make(
        velmux::core::ErrorCode::UnsupportedFeature,
        "whole-pipeline execution masked for test route selection", "test");
    return result;
  }
};

/// Wraps the real Apple backend. stages()/inspector()/initialize() forward
/// to the real object (the real AVAssetReader/VideoToolbox/AVAssetWriter
/// stage workers do all media work); capabilities() is narrowed so the
/// planner cannot build any route that uses the masked side, and executor()
/// refuses whole-pipeline runs.
class VLMXMaskedAppleBackend final : public velmux::backend::IBackend {
public:
  VLMXMaskedAppleBackend(velmux::apple::AppleBackend &real,
                         VLMXHybridDirection direction)
      : real_(real), direction_(direction) {}

  velmux::core::BackendId id() const override { return real_.id(); }
  std::string name() const override { return real_.name(); }
  velmux::core::Error initialize() override { return real_.initialize(); }

  velmux::core::BackendCapabilities capabilities() const override {
    auto caps = real_.capabilities();
    for (auto &video : caps.video) {
      if (direction_ == VLMXHybridDirection::FfmpegToApple) {
        // Apple keeps the ENCODE stage side only: no Apple single-backend
        // transcode, no Apple hybrid decode side.
        video.support.decode = false;
      } else {
        // Apple keeps the DECODE stage side only: no Apple single-backend
        // transcode, no Apple hybrid encode/mux side.
        video.support.encode = false;
      }
    }
    return caps;
  }

  velmux::backend::IInspector *inspector() override { return real_.inspector(); }
  velmux::backend::IPipelineExecutor *executor() override {
    return &refusing_;
  }
  velmux::backend::IStageBackend *stages() override { return real_.stages(); }

private:
  velmux::apple::AppleBackend &real_;
  VLMXHybridDirection direction_;
  VLMXRefusingExecutor refusing_;
};

