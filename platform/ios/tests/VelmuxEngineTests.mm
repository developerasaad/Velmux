static NSString *vlmxJsonStringField(NSString *json, NSString *field) {
  NSString *key = [NSString stringWithFormat:@"\"%@\":", field];
  NSRange at = [json rangeOfString:key];
  if (at.location == NSNotFound) {
    return nil;
  }
  NSUInteger pos = at.location + at.length;
  while (pos < json.length && [json characterAtIndex:pos] == ' ') {
    ++pos;
  }
  if (pos < json.length && [json characterAtIndex:pos] == '"') {
    NSRange end = [json rangeOfString:@"\""
                               options:0
                                 range:NSMakeRange(pos + 1,
                                                   json.length - pos - 1)];
    if (end.location == NSNotFound) {
      return nil;
    }
    return [json substringWithRange:NSMakeRange(pos + 1, end.location - pos - 1)];
  }
  NSUInteger stop = pos;
  while (stop < json.length) {
    unichar c = [json characterAtIndex:stop];
    if (c == ',' || c == '}') {
      break;
    }
    ++stop;
  }
  return [json substringWithRange:NSMakeRange(pos, stop - pos)];
}

