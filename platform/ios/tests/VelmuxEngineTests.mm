static BOOL vlmxFfmpegBackendPresent(VelmuxEngineHandle *engine) {
  char *raw = velmux_describe_backends(engine);
  if (raw == nullptr) {
    return NO;
  }
  NSString *described = [NSString stringWithUTF8String:raw];
  velmux_free_string(raw);
  return [described containsString:@"FFmpeg"];
}

/// One job run through the C facade: start, poll to a terminal state.
struct VLMXFacadeJob {
  std::string state;
  std::string outputPath;
  std::string error;
  std::string pipelineSummary;
};

static VLMXFacadeJob vlmxRunFacadeJob(VelmuxEngineHandle *engine,
                                      NSString *requestJson,
                                      NSTimeInterval timeout) {
  VLMXFacadeJob outcome;
  char *startedRaw = velmux_start_job(engine, requestJson.UTF8String);
  NSString *started =
      startedRaw != nullptr ? [NSString stringWithUTF8String:startedRaw] : @"";
  if (startedRaw != nullptr) {
    velmux_free_string(startedRaw);
  }
  NSString *jobId = vlmxJsonStringField(started, @"jobId");
  if (jobId == nil) {
    outcome.state = "failed";
    outcome.error = started.length > 0
                        ? std::string(started.UTF8String)
                        : std::string("startJob returned no payload");
    return outcome;
  }
  const NSTimeInterval deadline = [NSDate timeIntervalSinceReferenceDate] + timeout;
  for (;;) {
    char *raw = velmux_get_job(engine, jobId.UTF8String);
    NSString *snapshot =
        raw != nullptr ? [NSString stringWithUTF8String:raw] : @"";
    if (raw != nullptr) {
      velmux_free_string(raw);
    }
    NSString *state = vlmxJsonStringField(snapshot, @"state");
    if (state.length > 0) {
      outcome.state = state.UTF8String;
    }
    NSString *path = vlmxJsonStringField(snapshot, @"outputPath");
    if (path.length > 0) {
      outcome.outputPath = path.UTF8String;
    }
    NSString *summary = vlmxJsonStringField(snapshot, @"pipelineSummary");
    if (summary.length > 0) {
      outcome.pipelineSummary = summary.UTF8String;
    }
    NSString *error = vlmxJsonStringField(snapshot, @"error");
    if (error.length > 0) {
      outcome.error = error.UTF8String;
    }
    if ([state isEqualToString:@"completed"] ||
        [state isEqualToString:@"failed"] ||
        [state isEqualToString:@"canceled"]) {
      return outcome;
    }
    if ([NSDate timeIntervalSinceReferenceDate] > deadline) {
      outcome.state += " (timed out waiting for a terminal state)";
      return outcome;
    }
    [NSThread sleepForTimeInterval:0.05];
  }
}

// ---------------------------------------------------------------------------
// Real VideoToolbox encode probes (session creation = encoder availability)
// ---------------------------------------------------------------------------

static BOOL vlmxVtCanEncode(FourCharCode codecType) {
  VTCompressionSessionRef session = nullptr;
  // Creation with a null callback is the cheap availability probe; no
  // frames are encoded (the session is invalidated immediately).
  const OSStatus status = VTCompressionSessionCreate(
      kCFAllocatorDefault, 64, 64, codecType, nullptr, nullptr, nullptr,
      nullptr, nullptr, &session);
  if (status == noErr && session != nullptr) {
    VTCompressionSessionInvalidate(session);
    CFRelease(session);
    return YES;
  }
  return NO;
}

