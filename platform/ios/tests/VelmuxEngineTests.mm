@implementation VelmuxEngineTests

// An XCTest assertion macro needs the running test instance, so the shared
// duration check is an instance method (not a free function).
- (void)vlmxAssertDurationWithin:(std::int64_t)probedUs
                         expected:(std::int64_t)expectedUs
                            label:(NSString *)label {
  const std::int64_t toleranceUs = 500000;
  XCTAssertTrue(std::llabs(probedUs - expectedUs) <= toleranceUs,
                @"%@ duration %.1fms vs expected %.1fms", label,
                probedUs / 1000.0, expectedUs / 1000.0);
}

#pragma mark - 1. FFmpeg whole-pipeline transcode through the real engine

- (void)testFFtoF_engineTranscode {
  NSString *dir = [VLMXTestMedia freshWorkDirectory:@"fftof"];
  NSError *fixtureError = nil;
  VLMXGeneratedMedia *fixture = [VLMXTestMedia
      generateH264AacMp4AtPath:[dir stringByAppendingPathComponent:@"fixture.mp4"]
                         width:640
                        height:480
                     frameRate:24.0
                    frameCount:300
                         error:&fixtureError];
  XCTAssertNotNil(fixture, @"fixture generation failed: %@",
                  fixtureError.localizedDescription);
  if (fixture == nil) {
    return;
  }

  VelmuxEngineHandle *engine = vlmxCreateFacadeEngine(@"fftof-engine");
  // XCTAssertNotNil takes id (an ObjC object reference); the engine
  // facade handle is an opaque C struct pointer, so the nil check is an
  // explicit boolean assertion instead.
  XCTAssertTrue(engine != nullptr, @"engine construction failed");
  if (engine == nullptr) {
    return;
  }
  @try {
    // Without the FFmpeg backend there is no FFmpeg route to prove (the
    // engine would pick Apple VideoToolbox). Honest skip — CI runs both
    // with and without the pinned FFmpeg artifacts.
    if (!vlmxFfmpegBackendPresent(engine)) {
      XCTSkip(@"the engine was built without the FFmpeg backend "
              @"(VELMUX_FFMPEG_ROOT not set at pod install); the F->F "
              @"transcode path cannot be exercised");
    }

    // The explicit video+audio bitrates make stream copy invalid (a real
    // re-encode); preferSoftware biases the planner to FFmpeg.
    NSString *request = [NSString stringWithFormat:
        @"{"
         @"\"source\":{\"uri\":\"%@\",\"displayName\":\"fixture.mp4\"},"
         @"\"outputContainer\":\"mp4\","
         @"\"goal\":{\"kind\":\"custom\"},"
         @"\"video\":{\"codec\":\"h264\",\"enabled\":true,"
         @"\"rateControl\":\"bitrate\",\"bitRate\":800000},"
         @"\"audio\":{\"codec\":\"aac\",\"enabled\":true,\"bitRate\":64000},"
         @"\"subtitles\":{\"policy\":\"remove\"},"
         @"\"processingMode\":\"preferSoftware\""
         @"}",
        fixture.path];
    const VLMXFacadeJob job = vlmxRunFacadeJob(engine, request, 300.0);
    XCTAssertTrue([@"completed" isEqualToString:
                       [NSString stringWithUTF8String:job.state.c_str()]],
                  @"FFmpeg transcode failed: %s (summary: %s)",
                  job.error.c_str(), job.pipelineSummary.c_str());
    NSString *summary =
        [NSString stringWithUTF8String:job.pipelineSummary.c_str()];
    XCTAssertTrue([summary localizedCaseInsensitiveContainsString:
                        @"via ffmpeg"],
                  @"the planner did not route this through FFmpeg: \"%@\"",
                  summary);

    // INDEPENDENT validation: AVAsset probe of the produced file.
    NSString *outPath =
        [NSString stringWithUTF8String:job.outputPath.c_str()];
    XCTAssertGreaterThan([VLMXTestMedia fileSizeAtPath:outPath], (long long)0,
                         @"output missing or empty: %@", outPath);
    NSError *probeError = nil;
    VLMXMediaProbe *probe = [VLMXTestMedia probeAtPath:outPath
                                                 error:&probeError];
    XCTAssertNotNil(probe, @"probe failed: %@", probeError);
    if (probe != nil) {
      XCTAssertTrue([probe.videoCodec isEqualToString:@"avc1"] ||
                        [probe.videoCodec isEqualToString:@"avc3"],
                    @"expected H.264 video, got %@", probe.videoCodec);
      XCTAssertEqualObjects(probe.audioCodec, @"aac ",
                            @"expected AAC audio, got %@", probe.audioCodec);
      XCTAssertEqual(probe.width, fixture.width, @"geometry changed");
      XCTAssertEqual(probe.height, fixture.height, @"geometry changed");
      [self vlmxAssertDurationWithin:probe.durationUs
                              expected:fixture.durationUs
                                 label:@"FF->FF"];
    }
  } @finally {
    velmux_engine_destroy(engine);
  }
}

#pragma mark - 2. All-Apple stage pipeline through the real HybridExecutor

- (void)testNtoN_stageComposed {
  // The stage workers are real AVFoundation/VideoToolbox code; a simulator
  // runtime without an H.264 encoder cannot run this test.
  if (!vlmxVtCanEncode(kCMVideoCodecType_H264)) {
    XCTSkip(@"this simulator runtime has no VideoToolbox H.264 encoder");
  }

  NSString *dir = [VLMXTestMedia freshWorkDirectory:@"nton"];
  NSError *fixtureError = nil;
  VLMXGeneratedMedia *fixture = [VLMXTestMedia
      generateH264AacMp4AtPath:[dir stringByAppendingPathComponent:@"fixture.mp4"]
                         width:320
                        height:240
                     frameRate:24.0
                    frameCount:120
                         error:&fixtureError];
  XCTAssertNotNil(fixture, @"fixture generation failed: %@",
                  fixtureError.localizedDescription);
  if (fixture == nil) {
    return;
  }

  NSString *outPath = [dir stringByAppendingPathComponent:@"out-nton.mp4"];

  // Real Apple backend; the HybridExecutor composes its stage workers.
  velmux::apple::AppleBackend apple;
  const auto initError = apple.initialize();
  if (!initError.ok()) {
    XCTSkip(@"Apple media stack unavailable in this process: %s",
            initError.message.c_str());
  }

  velmux::core::Pipeline pipeline;
  const auto assign = [&pipeline](velmux::core::StageId stage) {
    pipeline.stages.push_back({stage, velmux::core::BackendId::Apple});
  };
  assign(velmux::core::StageId::Demux);
  assign(velmux::core::StageId::Decode);
  assign(velmux::core::StageId::VideoProcessing);
  assign(velmux::core::StageId::AudioProcessing);
  assign(velmux::core::StageId::Encode);
  assign(velmux::core::StageId::Mux);
  assign(velmux::core::StageId::Bitstream);
  pipeline.videoCodec = velmux::core::VideoCodec::H264;
  pipeline.audioCodec = velmux::core::AudioCodec::Aac;
  pipeline.container = velmux::core::Container::Mp4;
  pipeline.sourceFrameRate = fixture.frameRate;
  pipeline.videoStreamCopy = false;
  pipeline.audioStreamCopy = true; // the Apple mux stage copies the AAC

  velmux::core::ConversionRequest request;
  request.source.uri = std::string(fixture.path.UTF8String);
  request.source.displayName = "fixture.mp4";
  request.outputContainer = velmux::core::Container::Mp4;
  request.goal.kind = velmux::core::GoalKind::Custom;
  request.video.enabled = true;
  request.video.codec = velmux::core::VideoCodec::H264;
  request.video.rateControl = velmux::core::RateControl::Bitrate;
  request.video.bitRate = 800000;
  request.audio.enabled = true;
  request.audio.codec = velmux::core::AudioCodec::Aac;
  request.subtitles.policy = velmux::core::SubtitlePolicy::Remove;
  request.processingMode = velmux::core::ProcessingMode::Auto;

  velmux::core::HybridExecutor hybrid({&apple});
  XCTAssertTrue(hybrid.canExecute(pipeline, request),
                @"the all-Apple stage pipeline must be hybrid-executable");

  velmux::backend::ExecuteParams params;
  params.pipeline = pipeline;
  params.request = request;
  params.outputPath = std::string(outPath.UTF8String);
  params.jobId = "velmux-test-nton";
  params.cancel = std::make_shared<velmux::backend::CancelToken>();
  params.onProgress = [](const velmux::backend::ProgressReport &) {};
  const velmux::backend::ExecuteResult result = hybrid.execute(params);
  XCTAssertTrue(result.success, @"hybrid execution failed: %s",
                result.error.message.c_str());
  XCTAssertGreaterThanOrEqual(result.framesProcessed,
                              (std::int64_t)fixture.frameCount,
                              @"fewer frames processed than the fixture has");

  // INDEPENDENT validation: AVAsset probe + real frame decode.
  XCTAssertGreaterThan([VLMXTestMedia fileSizeAtPath:outPath], (long long)0,
                       @"output missing or empty: %@", outPath);
  NSError *probeError = nil;
  VLMXMediaProbe *probe = [VLMXTestMedia probeAtPath:outPath
                                               error:&probeError];
